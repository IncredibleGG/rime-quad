// windows/common/bar_owner.h — 那一橫此刻是「誰的」(§12.10.6 的收斂層)
//
// ── 這一支解的是哪一句話寫錯了作用域 ────────────────────────────
//
// 那一橫的判準只有一句:
//
//   **它只在「使用者此刻輸入焦點所在的那一條宿主執行緒上,啟用中的
//   TSF profile 是我們」的時候顯示。**
//
// 不是「有沒有人連著我們」,不是「有幾個宿主載入了我們」,也不是
// 「系統當前的輸入法是不是我們」。上一輪的判準問的是**有沒有人**
// (`active_clients > 0`),而該問的是**這一個人是不是他**。
//
// 使用者實機回報的四個症狀裡有兩個是同一句話寫錯作用域的兩個方向:
//
//   S1 切到我們之後、還沒打字,那一橫不在。
//      → 條件其實成立,而我們**看不到**它(ActivateEx 不開任何連線)。
//   S4 已經切到微軟拼音了,那一橫還自己冒出來。
//      → 焦點那條執行緒上條件不成立,而我們把**別人的**條件當成自己的
//        (「有幾條管道 handle 開著」是一個沒有產品意義的量)。
//
// 而 S2(打字時時有時無)是第三個方向:焦點以前是**單一全域布林**,
// 由「最後說話的那個宿主」寫 —— 背景宿主一進場就把前景那個蓋掉。
//
// ── 三個層次,不是三個選項 ──────────────────────────────────────
//
//   1. **宿主提案。** 只有宿主自己知道「這條執行緒上啟用中的 profile
//      是不是我們」—— 服務端問不到別的進程的 TSF 狀態
//      (ITfInputProcessorProfileMgr 是 per-thread、per-process 的)。
//      宿主表達的方式是**在場連線的生死**:ActivateEx 開、
//      Deactivate 或 profile 被換掉時關。連線在 = 「我這條執行緒上是我們」。
//   2. **服務裁決。** 13 個宿主同時提案,收斂成一個答案的規則就是本檔。
//      ⚠ 逐連線 OR(上一輪的做法)是**單調沾黏**的:任何一條洩漏的連線
//        把那一橫永久釘住,而那正是 S4。
//   3. **系統打平手。** 誰是前景由 OS 回答,不由 13 個宿主各自宣稱 ——
//      讓宿主自己說「我是前景」的話,兩個宿主同時說 true 就退化回 OR。
//      OS 也是唯一**不依賴宿主活著、不依賴宿主誠實**的一方:被凍結的
//      UWP 進程、來不及送 Deactivate 就被砍掉的宿主,都靠這一層擋。
//
// ── #111:上一版把「查不到」讀成「是別人的」──────────────────────
//
// 上面第 1 層寫著「宿主表達的方式是**在場連線的生死**」,而那句話有一個
// 沒說出口的前提:**每一個前景執行緒都會有一條在場連線**。它不成立:
//
//   · 截圖工具(Snipaste)、工作列、桌面 —— 它們從來不載入我們的 TIP,
//     一條在場連線都不會有,而截圖框選會佔住前景遠超過 3000 毫秒。
//   · 更嚴重的一種,是使用者的 tsf.log 這一次才證實的:**在升級前就
//     開著的宿主行程,直到它自己重開之前都還抱著舊的 rime_tsf.dll**,
//     而舊 DLL 沒有在場連線這回事。Explorer.exe(工作列、檔案總管)
//     幾乎永遠不會重開 —— 這不是偶發,是使用者桌面上一半的程式。
//
// 於是「這條執行緒上沒有在場連線」的真正意思是**「我不知道」**,而上一版
// 把它讀成「是別人的」→ in_use=false → 3 秒後隱藏。
//
// 這一版把那一格拆成兩態,而**隱藏需要正面證據**:宿主必須明確說出
// 「這條執行緒上啟用中的不再是我們」(protocol.h 的 kProfileState),
// 而那句證據存在服務端、鍵是 tid、活得比連線久(BarOwnerYield)。
//
// ⚠ 這樣做會不會把 S4 放回去?不會 —— 收起來的觸發點還是同一個:
//   profile sink 的非啟用邊(text_service.cc 的 OnActivated)。一個邊都
//   沒少,只是它的表達方式從「把連線關掉」(與宿主死掉同一個事件)
//   換成「說一句話」(只有這一件事會產生它)。
//
// ── 為什麼是純函式 ──────────────────────────────────────────────
//
// 三輪壞掉的都不是「判準寫錯」,是「送到判準面前的那份答案錯了」。
// grep 守得住「這一行還在嗎」,守不住「13 個宿主怎麼收斂成一個答案」。
// 這一支收在 common/ 就是為了讓 S4 那個方向在 Ubuntu 上擋得住 ——
// tests/test_bar_owner.cc 直接把 12 條殭屍 + 1 條前景餵進來。
//
#ifndef RIMEWIN_COMMON_BAR_OWNER_H_
#define RIMEWIN_COMMON_BAR_OWNER_H_

#include <cstddef>
#include <cstdint>
#include <vector>

namespace rimewin {

// 服務端手上的**一條連線**。一個宿主可以有兩條(在場一條、按鍵一條)。
struct BarOwnerClient {
  // 服務端自己發的流水號。只用來讓答案是確定的(不會在兩條同分的
  // 連線之間跳來跳去),沒有別的意義。
  uint64_t client_id = 0;
  uint32_t host_pid = 0;
  // ⚠ **啟用我們的那一條 TSF 執行緒**,不是宿主的主執行緒。
  //   輸入法在 Windows 上是 per-thread 的(系統設定裡「讓我為每個
  //   應用程式視窗使用不同的輸入法」把這件事做成使用者看得見的事實),
  //   所以作用域必須是執行緒。0 = 這個用戶端報不出來(舊 DLL)。
  uint32_t host_tid = 0;
  // 這條連線的 librime session。0 = 還沒建(在場連線一直是 0)。
  // 那一橫回讀中英狀態時要問**這一個**,不是隨便挑一個活著的。
  uint64_t session = 0;
  // 握過手了嗎。⚠ **沒握手的連線一票都不投**:服務端在讀到第一個
  //   位元組之前就已經有一條連線了(ClientTicket 建構在 ServeClient
  //   最頂端),而那時我們連它是不是我們自己的 DLL 都不知道。
  bool activated = false;
};

// OS 這一刻說前景是誰。由服務端自己去問,不接受宿主宣稱。
struct BarOwnerForeground {
  // ⚠ 假 = **問不出來**(安全桌面 / UAC 提示時 GetForegroundWindow()
  //   回 NULL)。那時候**不要改狀態** —— 見 BarOwnerDecision::undecidable。
  bool known = false;
  uint32_t pid = 0;
  uint32_t tid = 0;
  // ── UWP:前景視窗不是宿主的 ──────────────────────────────────
  //
  // 使用者在一個 UWP app 裡打字時,GetForegroundWindow() 回的是
  // ApplicationFrameHost.exe 的框視窗 —— pid 與 tid 都**不是**真正的
  // 宿主。真正的宿主握著那個框底下的 Windows.UI.Core.CoreWindow。
  // 少了這一層,「使用者正在 UWP app 裡打字」會被判成沒有人在用。
  bool inner_known = false;
  uint32_t inner_pid = 0;
  uint32_t inner_tid = 0;
  // ── 服務**自己**的 pid ──────────────────────────────────────
  //
  // ⚠ 由呼叫端填(status_bar.cc 的 ReadForegroundOwner 一行
  //   ::GetCurrentProcessId()),不是在這裡去問 —— 這一支是純函式,
  //   而「誰是我們自己」必須餵得進來才測得到。0 = 沒填,那一格就不比。
  //
  // 為什麼要有這一格:服務自己也有視窗(設定視窗、托盤選單、那一橫
  // 自己的方案彈出選單)。使用者從那一橫點「設定」,前景就變成**服務
  // 自己的進程、自己的執行緒** —— 13 個宿主一筆都對不上。少了這一格,
  // 那等於「沒有人在用」:3000 毫秒之後那一橫在他眼前消失,而他做的
  // 事只是打開設定。見 BarOwnerDecision::undecidable 的第二個原因。
  uint32_t service_pid = 0;
  // ── 前景那條執行緒此刻**收不收得到文字** ──────────────────────
  //
  // 由呼叫端填(status_bar.cc 的一次 GetGUIThreadInfo:有 hwndFocus
  // 就是真)。桌面、工作列、截圖疊層這種前景**沒有鍵盤焦點視窗**,
  // 而它們代表的不是「使用者換了輸入法」,只是「他此刻沒有在任何
  // 地方打字」。
  //
  // ⚠ 預設 false = **不知道**,而且只有「隱藏」那一條路要求它為真。
  //   方向是刻意的:忘了餵料(或 UIPI 讓 GetGUIThreadInfo 對提權宿主
  //   回 FALSE)的後果是「那一橫留著」,不是「那一橫亂收」。
  bool can_take_text = false;
};

// 那一橫這一刻該怎麼辦。
//
// ⚠ **三態,不是布林。** 「前景不是我們的」與「這個前景答不出這個問題」
//   是兩件完全不同的事,而上一版把它們混成同一個 in_use=false ——
//   那正是 #111:截圖工具、工作列、桌面、以及**每一個在升級前就開著、
//   還抱著舊 DLL 的宿主**(它們一條在場連線都沒有)全部被讀成「別人的」,
//   於是那一橫在使用者眼前消失。
enum class BarOwnerVerdict : uint8_t {
  // 前景那條執行緒上啟用中的是我們 → 顯示。
  kOurs,
  // 前景那條執行緒上啟用中的**不是**我們,而且這是宿主**說出來的**,
  // 不是我們從「查不到」推出來的 → 隱藏。
  kTheirs,
  // 答不出來 → **維持上一次的判斷**。這一格刻意很寬:查不到就落在這裡。
  kHold,
};

// 「某一條執行緒明確說過它讓位了」這件事的載體。
//
// ⚠ 它**必須活得比連線久**。TSF 很可能在讓位之後緊接著把那條執行緒上的
//   TIP 也 Deactivate 掉,連線會死;證據不可以跟著死,否則服務端又退回
//   只能從「查不到」推論的狀態 —— 也就是 #111 本身。所以鍵是 tid、
//   存在 StatusBar(status_bar.h 的 yields_),不掛在連線物件上。
struct BarOwnerYield {
  uint32_t host_tid = 0;
  // 單調時鐘(GetTickCount64)。過期規則見 BarOwnerYieldTtlMs()。
  uint64_t at_ms = 0;
};

// 一筆讓位紀錄能活多久(毫秒)。
//
// ⚠ tid 會被系統回收,所以這筆證據不能永久有效。過期之後回到 kHold =
//   維持當下,而當下本來就是隱藏 —— 過期本身製造不出任何可見的錯,
//   它只把「拿一個被回收的 tid 當成別人的」那個窗口關掉。
uint32_t BarOwnerYieldTtlMs();

struct BarOwnerDecision {
  // ⚠ 真 = **這一刻的前景回答不了「那一橫該不該顯示」這個問題**。
  //   呼叫端**維持現狀** —— 不要把它讀成「沒有人在用」。
  //
  //   兩個原因,而兩個都是使用者看得到的事:
  //     1. **OS 答不出前景**(UAC 提示、安全桌面、切換桌面的那一瞬)。
  //        他只是被問了一次系統權限,那一橫不該開始倒數消失,
  //        而 3000 毫秒的遲滯(common/bar_visibility.h)本來就壓得住。
  //     2. **前景是服務自己的視窗**(設定視窗、托盤選單、那一橫自己
  //        的彈出選單)。服務不是一個宿主,它答不了「使用者在哪一個
  //        宿主裡打字」這個問題。使用者從那一橫點「設定」→ 視窗開
  //        起來 → 3000 毫秒後那一橫不見,就是少了這一格的樣子。
  //
  //   ⚠ 名字不叫 os_unknown:第 2 個原因底下 OS 答得完全正確,
  //     而這個 codebase 已經吃過好幾次「名字說的比實際窄一階」的虧。
  //
  //   ⚠ #111 之後,這一格的**第 3 個原因才是最常見的那一個**:
  //     前景那條執行緒上查不到任何在場連線。以前那走的是「別人的」,
  //     現在走這裡。收起來需要正面證據 —— 見 verdict。
  bool undecidable = false;
  // 使用者此刻正在用的那條執行緒上,啟用中的是不是我們。
  bool in_use = false;
  // ── 三態的具名版本。undecidable ≡ (verdict == kHold),
  //    in_use ≡ (verdict == kOurs) —— 那兩個布林保留原名原義,因為
  //    呼叫點(status_bar.cc)與守門(audit_single_source.sh)都逐字
  //    綁著它們。verdict 存在的理由是**記錄寫得出「為什麼」**:
  //    兩個布林拼不出「他切走了」與「這個前景我不認識」的差別。
  BarOwnerVerdict verdict = BarOwnerVerdict::kHold;
  // kHold 時,是哪一種答不出來 —— 只給記錄用,判斷一律只看 verdict。
  enum class HoldReason : uint8_t {
    kNone,            // verdict != kHold
    kForegroundUnknown,   // OS 答不出前景(UAC / 安全桌面)
    kForegroundIsService, // 前景是服務自己的視窗
    kNoPresenceOnThread,  // 那條執行緒上查不到在場連線,也沒說過讓位
    kYieldedButNoFocus,   // 說過讓位,但那條執行緒此刻收不到文字
  };
  HoldReason hold_reason = HoldReason::kNone;
  // 那一條連線是誰。0 = 沒有。
  uint64_t focused_client = 0;
  // 它的 session。0 = 它還沒建 session(切過來但還沒打字)。
  uint64_t focused_session = 0;
};

// ── 收斂規則(逐條,而且每一條都有一支測試)────────────────────
//
//   · OS 答不出前景          → kHold,呼叫端維持現狀
//   · 前景是**服務自己**      → 同上。設定視窗不是一個宿主,
//     (設定視窗 / 托盤選單)     那一刻不代表「沒有人在用」
//   · 沒握手的連線            → 一票都不投
//   · 報得出 tid 的連線       → **只**比 tid。報得出來卻退回去比 pid,
//                              等於在 per-app-window 模式下再壞一次
//   · 報不出 tid 的連線(舊 DLL)→ 才退回去比 pid
//   · UWP:框視窗比不上時,再比 CoreWindow 那一層
//   · 同分時:先挑**有 session 的**那一條(在場連線與按鍵連線並存時,
//     要回讀的是有 session 的那一條),再挑 client_id 最小的 ——
//     答案必須是確定的,不可以在兩條之間跳
//   · 一條都對不上時 → **不再直接判成「別人的」**(那是 #111):
//       - 那條執行緒送過還沒過期的讓位紀錄,**而且**它此刻收得到文字
//         → kTheirs(隱藏)
//       - 其餘一律 kHold(維持)
//
// ⚠ yields 為什麼是引數而不是狀態:過期判斷要跟收斂規則住在一起,
//   才在這台 Ubuntu 上測得到(status_bar.cc 在 Linux 上編不起來)。
//   now_ms 同理 —— 純函式不可以自己去問時鐘。
BarOwnerDecision DecideBarOwner(const std::vector<BarOwnerClient>& clients,
                                const std::vector<BarOwnerYield>& yields,
                                const BarOwnerForeground& fg, uint64_t now_ms);

}  // namespace rimewin

#endif  // RIMEWIN_COMMON_BAR_OWNER_H_

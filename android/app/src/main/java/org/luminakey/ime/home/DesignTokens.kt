package org.luminakey.ime.home

import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/*
 * App 這一側的設計語彙。**`docs/ui-design.md` §3 的 Kotlin 版本。**
 *
 * ── 為什麼要有這個檔案 ──────────────────────────────────────────────────
 * 規範量過現況：App 側用了 **26 種 `.dp` 字面值、17 種 `.sp`**（§3.1 的實測表）。
 * 26 種間距不是「比較有彈性」，是**沒有人決定過**：24 與 26 之間沒有人看得出
 * 差別，但它保證四端、四個畫面、四個人各自漂移，而且永遠對不回來。
 *
 * 所以這裡把階梯寫成**名字**。之後畫面上不再出現裸的數字，要調間距就是換一階；
 * 需要一個階梯上沒有的值時，**改這個檔案並通知四端**，不要在單一畫面上例外。
 *
 * ── 三個集合各管各的（§3.1「F1 的範圍」）────────────────────────────────
 * `.dp` 不是全都是間距。混在一起掃會把 1dp 的分隔線判成違規，
 * 而**一條永遠紅的檢查會被關掉**，那比沒有這條檢查更糟。所以拆成三個：
 *
 *   · [Space]  間距 —— padding、spacedBy、Spacer
 *   · [Radius] 圓角 —— RoundedCornerShape
 *   · [Dimens] 元件尺寸 —— height、heightIn(min=)、線寬
 *
 * `DesignTokenTest` 照這三個集合掃 `home/` 與 `store/StoreScreen.kt`。
 */

/**
 * 間距，八階，**沒有第九階**（§3.1）。
 *
 * 兩條用法規則，比數值本身重要：
 *   1. **同一組東西之間的距離，必須小於它們與外面的距離。** 這是「分組」唯一
 *      可靠的手段 —— 比框線、比顏色、比分隔線都可靠。分隔線只是輔助。
 *   2. **不要用兩個相鄰的階數表達不同的意思。** 看不出差別的差別等於沒有差別。
 */
object Space {
    /**
     * 標題與它正下方的副標。
     *
     * **這是唯一不是 4 的倍數的一階** —— 4dp 會讓那兩行看起來不像同一組。
     */
    val s1 = 2.dp

    /** 圖示與它的文字之間。 */
    val s2 = 4.dp

    /** 同一組控制項彼此之間；小標題與它管的控制項之間。 */
    val s3 = 8.dp

    /** 卡片內一列的上下 padding。 */
    val s4 = 12.dp

    /** 卡片內的左右 padding；卡片與卡片之間。 */
    val s5 = 16.dp

    /** 畫面左右邊距。 */
    val s6 = 20.dp

    /** 區塊與區塊之間（有小標題的那種）。 */
    val s7 = 24.dp

    /** 頁面頂端與底端的留白。 */
    val s8 = 40.dp
}

/**
 * 字級，六階，**沒有第七階**（§3.2）。
 *
 * ⚠ **字級只表示層級，不表示重要性。** 「這個很重要」用位置（放上面）與顏色
 * （重點色）表示，不要放大字級 —— 放大之後下一個重要的東西就沒有階可以用了。
 */
object TypeScale {
    /** 頁標題。每頁最上面那一行，**一頁只有一個**；第二層不用它（用 [t2]）。 */
    val t1 = 27.sp

    /** 區段標題：第二層的頁首、對話框標題。 */
    val t2 = 17.sp

    /** 列標題：設定項的名字、卡片內的主要文字。**永遠一行，長了就截尾。** */
    val t3 = 16.sp

    /** 現值：列右側的現值、按鈕文字。 */
    val t4 = 13.5.sp

    /** 說明：白話說明、小標題、輔助文字。 */
    val t5 = 12.5.sp

    /** 診斷。**只有**診斷區塊用它，而且一律等寬字、一律英文（§4.11）。 */
    val t6 = 12.sp

    /* 行高：只有多行才需要，所以不是每一階都有。單行的字給行高沒有意義。 */

    /** [t1] 的行高。 */
    val t1Line = 34.sp

    /** [t3] 的行高（鍵盤卡的標題會折兩行）。 */
    val t3Line = 20.sp

    /** [t5] 的行高（白話說明常常兩句）。 */
    val t5Line = 18.sp
}

/**
 * 圓角，四個值，巢狀時內層 = 外層 − 2~5（§3.3）。
 *
 * **按鈕的圓角跟平台走，不跟我們走** —— 一顆長得不像 Android 按鈕的按鈕，
 * 使用者不會確定它按不按得下去，這比「風格統一」重要。所以這裡沒有按鈕。
 */
object Radius {
    /** 卡片、對話框、面板。 */
    val large = 16.dp

    /** 分段控制外框、晶片、輸入框。 */
    val medium = 11.dp

    /** 分段控制**被選中**的那一格（= [medium] − 2）。 */
    val mediumInner = 9.dp

    /** 圖示容器、縮圖、進度條。 */
    val small = 8.dp
}

/** 元件尺寸。**不是間距**，所以不受 [Space] 的階梯管（§3.1「F1 的範圍」）。 */
object Dimens {
    /** 分隔線。1dp 而不是 hairline，因為 §3.4.1 的對比度是照 1dp 實心算的。 */
    val hairline = 1.dp

    /**
     * 觸控目標下限（§3.6）。
     *
     * 低於這個值的可點區域在真機上會變成「要按兩三次才中」，而自動化完全測不到
     * —— 它在模擬器上用滑鼠點永遠是準的。
     */
    val touchTarget = 48.dp

    /** 設定列的最小高度：兩行文字（t3 + t5）加上下 padding。 */
    val row = 58.dp

    /** 進度條高度。 */
    val progress = 4.dp

    /** 步驟編號那顆圓圈。 */
    val stepBadge = 24.dp
}

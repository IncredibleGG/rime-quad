package org.luminakey.ime.core

/**
 * 「整理字詞要等多久」—— **全專案只有這裡有那個數字**。
 *
 * ── 為什麼要一個常數，而不是各處各寫各的 ────────────────────────────────
 * 稽核之前這件事散在七個地方，而且**互相矛盾**：引導頁的進度條用 12500、
 * 首頁與引導頁的文案寫「about ten seconds」、鍵盤上那句寫「一到兩分鐘」、
 * 市集的說明寫 7.2。使用者在同一次首次啟動裡至少會看到其中三句 ——
 * 那不只是不一致，是讓他**無法判斷現在是不是卡住了**：說十秒的畫面等了
 * 十三秒，他會認定壞了；說兩分鐘的畫面十秒就好，他會覺得這 app 亂講。
 *
 * ── 量測來源（挑這個數字的依據）────────────────────────────────────────
 * 同一條路徑（首次啟動：解壓隨附資料 → librime 編三本詞庫 + 5.7MB 語言模型）
 * 留下過三個實測值：
 *   · 三星 S24U（實體機）首次啟動          12500 ms  ← 採用
 *   · x86_64 模擬器 首次啟動                8000 ms
 *   · 市集裝完之後重新部署三個方案          7200 ms
 * 取**最慢的實體機首次**：使用者實際在等的就是這一個；而且低估比高估更傷 ——
 * 提早好是驚喜，晚了才是故障。
 *
 * ⚠ 這個數字改了以後，三種語言的文案會**一起**跟著改，因為文案裡那個數字是
 * placeholder，值從 [TYPICAL_SECONDS] 來。**不要在字串或註解裡另外寫死秒數**，
 * `DeployEstimateTest` 會擋下來。
 */
object DeployEstimate {

    /** 首次部署的預期耗時（毫秒）。引導頁那條進度線拿它當分母。 */
    const val TYPICAL_MS: Long = 12_500L

    /**
     * 給文案用的秒數，**無條件進位**。
     *
     * 進位而不是四捨五入：文案講的是「大約 n」，多說一點的代價是使用者提早
     * 拿到好消息，少說一點的代價是他在最後那一下認定它壞了。
     */
    val TYPICAL_SECONDS: Int = ((TYPICAL_MS + 999) / 1000).toInt()
}
